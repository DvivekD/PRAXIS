// Generator function to produce the rest of the 120 backlog tickets
function generateFullQueue(baseTickets: SupportTicket[]): SupportTicket[] {
  const fullQueue: SupportTicket[] = [...baseTickets];
  const companies = [
    { name: "Apex Retailers", domain: "apexretail.com", tier: "Growth Enterprise" as const, arr: "$65,000 ARR" },
    { name: "Cobalt Analytics", domain: "cobalt.io", tier: "Scale" as const, arr: "$40,000 ARR" },
    { name: "Pinnacle Brands", domain: "pinnaclebrands.co", tier: "Enterprise VIP" as const, arr: "$190,000 ARR" },
    { name: "Solstice Energy", domain: "solstice.energy", tier: "Growth Enterprise" as const, arr: "$78,000 ARR" },
    { name: "Vanguard Tech", domain: "vanguardtech.dev", tier: "Scale" as const, arr: "$35,000 ARR" },
    { name: "Zephyr Cloud", domain: "zephyr.cloud", tier: "Starter" as const, arr: "$12,000 ARR" },
  ];

  const firstNames = ["James", "Emma", "Daniel", "Mia", "Alexander", "Olivia", "Benjamin", "Charlotte", "Ethan", "Amelia"];
  const lastNames = ["Wilson", "Taylor", "Anderson", "Thomas", "Jackson", "White", "Harris", "Martin", "Thompson", "Garcia"];

  let nextId = 4909;
  while (fullQueue.length < 120) {
    const fn = firstNames[fullQueue.length % firstNames.length];
    const ln = lastNames[Math.floor(fullQueue.length / firstNames.length) % lastNames.length];
    const comp = companies[fullQueue.length % companies.length];
    const isIncidentRelated = fullQueue.length < 60; // First 60 tickets relate to the duplicate charge storm
    const slaSec = 300 + (fullQueue.length * 35) % 1800;

    fullQueue.push({
      id: `TICK-${nextId}`,
      customer: `${fn} ${ln}`,
      company: comp.name,
      email: `${fn.toLowerCase()}.${ln.toLowerCase()}@${comp.domain}`,
      avatar: `${fn[0]}${ln[0]}`,
      tier: comp.tier,
      arr: comp.arr,
      subject: isIncidentRelated
        ? `Double charge detected on checkout ord_${nextId + 5000}`
        : `Order tracking inquiry for ord_${nextId + 5000}`,
      orderId: `ord_${nextId + 5000}`,
      amount: isIncidentRelated ? `$${(95 + (nextId % 200)).toFixed(2)} (x2 duplicate)` : `$${(80 + (nextId % 150)).toFixed(2)}`,
      rawAmount: 95 + (nextId % 200),
      priority: isIncidentRelated ? (slaSec < 400 ? "CRITICAL" : "HIGH") : (slaSec < 500 ? "HIGH" : "NORMAL"),
      slaTotalSeconds: slaSec + 300,
      slaRemainingSeconds: Math.max(25, slaSec),
      status: "OPEN",
      channel: (["portal", "email", "chat"] as const)[nextId % 3],
      tags: isIncidentRelated ? ["DOUBLE_CHARGE", "BLACK_FRIDAY_SURGE"] : ["GENERAL_INQUIRY"],
      message: isIncidentRelated
        ? `Double charged on checkout during the sale. Transaction pending. Please refund duplicate.`
        : `Requesting expedited tracking information on shipment dispatched this afternoon.`,
      orderHistoryCount: (nextId % 8) + 1,
      duplicateTxId: `tx_${nextId + 4000}`,
      originalTxId: `tx_${nextId + 3999}`,
      isBreached: false,
      createdAt: `17:${(nextId % 40).toString().padStart(2, "0")} UTC`,
    });
    nextId++;
  }

  return fullQueue;
}

